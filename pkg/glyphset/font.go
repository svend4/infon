// fontMask returns the 5×7 bitmap rows for a rune (lower-case is folded to upper),
// and whether the rune is in the font.
func fontMask(r rune) ([]string, bool) {
	if r >= 'a' && r <= 'z' {
		r -= 32
	}
	rows, ok := font5x7[r]
	return rows, ok
}

// IsText reports whether r is renderable as font text (vs a block/triangle glyph).
func IsText(r rune) bool {
	_, ok := fontMask(r)
	return ok && !strings.ContainsRune(" ", r)
}
