// solanMask returns a rune's bitmap rows and pixel width in the Solan font (case
// is significant — it defines distinct upper/lower glyphs), and whether present.
func solanMask(r rune) ([]uint16, int, bool) {
	g, ok := solanFont[r]
	return g.rows, g.w, ok
}
